/* Limelight nav — slides a light bar to the active sidebar item.
   Works with the existing scrollspy that toggles .active on a.scroll-link. */
(() => {
    const nav = document.querySelector('.sidebar-tools .nav-list');
    if (!nav) return;
    const links = [...nav.querySelectorAll('a.item-link')];
    if (!links.length) return;

    const light = document.createElement('span');
    light.className = 'nav-limelight';
    light.setAttribute('aria-hidden', 'true');
    nav.append(light);

    let current = null;
    const move = (el, instant) => {
        if (!el) return;
        current = el;
        const navBox = nav.getBoundingClientRect();
        const box = el.getBoundingClientRect();
        const top = box.top - navBox.top + (box.height - light.offsetHeight) / 2;
        if (instant) light.style.transition = 'none';
        light.style.top = top + 'px';
        light.style.opacity = '1';
        if (instant) requestAnimationFrame(() => { light.style.transition = ''; });
    };

    /* Clicking a link starts a smooth scroll that takes a while to arrive.
     * Meanwhile the scrollspy in main.js keeps recomputing .active from the
     * CURRENT scroll position — which is still the old section — and takes the
     * class straight back off the link the user just clicked. The light then
     * snaps back, and only a second click (once the scroll has landed) appears
     * to work. So after a click we hold the clicked link lit and re-assert it
     * against the scrollspy until the scroll settles.
     */
    let lockedLink = null;
    let lockUntil = 0;
    let asserting = false;      // guards the observer against its own writes

    const releaseLock = () => { lockedLink = null; lockUntil = 0; };
    const locked = () => lockedLink && Date.now() < lockUntil;

    const syncActive = () => {
        if (locked()) {
            // Re-assert: the scrollspy recomputes .active from the CURRENT
            // scroll position, which during a smooth scroll is still somewhere
            // between the old section and the new one.
            assertLocked();
            return;
        }
        if (lockedLink) releaseLock();
        const active = nav.querySelector('a.item-link.active');
        if (active && active !== current) move(active);
    };

    const assertLocked = () => {
        if (!lockedLink) return;
        if (nav.querySelector('a.item-link.active') !== lockedLink) {
            asserting = true;
            setActive(lockedLink);
            asserting = false;
        }
        if (current !== lockedLink) move(lockedLink);
    };

    // Click must couple all three active effects (sliding bar, green color,
    // icon/dot glow) to the same instant — otherwise the bar slides to an item
    // that only lights up later, when the scrollspy finally toggles .active.
    const setActive = (link) => {
        links.forEach((l) => l.classList.toggle('active', l === link));
    };
    /* Registered in the CAPTURE phase on the CONTAINER, not on each link.
     *
     * kdcv-interaction-fix.js — generated, so not editable here — attaches its
     * own capture-phase handler to the individual links and calls
     * stopImmediatePropagation(). Capture travels root -> target, so a listener
     * on the parent runs BEFORE one on the link, which is the only position
     * from which the click can still be observed on these pages. It records
     * intent only: no preventDefault, no stopPropagation, so the generated
     * handler's own scrolling behaviour is untouched.
     */
    nav.addEventListener('click', (event) => {
        const link = event.target.closest && event.target.closest('a.item-link');
        if (!link || !links.includes(link)) return;
        lockedLink = link;
        lockUntil = Date.now() + 1400;   // longer than the smooth scroll
        asserting = true;
        setActive(link);
        asserting = false;
        move(link);
    }, true);

    /* THE CLICK LISTENER ABOVE DOES NOT RUN ON THE CV PAGES.
     *
     * kdcv-interaction-fix.js — generated by the tooling, so it cannot be
     * edited here — registers its own CAPTURE-phase click handler on these same
     * links and calls event.stopImmediatePropagation(). That discards every
     * other listener on the element, including this one. It then does its own
     * `.active` bookkeeping (clear all, set the clicked link) and smooth-scrolls.
     *
     * Net effect before this fix: the icon turned green because the generated
     * script moved the class, but the light bar never moved because move() was
     * never reached — so the light sat on the previously-clicked item.
     *
     * An observer cannot be stopImmediatePropagation'd. Watching the class
     * attribute means the light follows `.active` no matter WHO sets it: this
     * module, the generated fix, or main.js's scrollspy. The click listener is
     * kept for pages where the generated script is absent.
     */
    if ('MutationObserver' in window) {
        new MutationObserver(() => {
            if (asserting) return;      // our own write; nothing to react to
            // setTimeout, not rAF: rAF is paused while the tab is hidden, and
            // the class can change from a background scroll handler.
            window.setTimeout(() => {
                if (locked()) {
                    // A click is in flight. Whoever just moved .active — the
                    // generated handler or the scrollspy mid-scroll — does not
                    // get to steal the light from the item the user chose.
                    // This used to call releaseLock() here, which meant the
                    // lock never survived a single mutation and the light
                    // chased the scroll instead of leading it.
                    assertLocked();
                    return;
                }
                const active = nav.querySelector('a.item-link.active');
                if (active && active !== current) move(active);
            }, 0);
        }).observe(nav, { subtree: true, attributes: true, attributeFilter: ['class'] });
    }

    // Any deliberate scroll input means the user has taken over; drop the lock
    // immediately so manual scrolling is never fought by the click state.
    ['wheel', 'touchstart', 'keydown'].forEach((evt) => {
        window.addEventListener(evt, releaseLock, { passive: true });
    });
    document.addEventListener('scroll', () => requestAnimationFrame(syncActive), { passive: true });
    window.addEventListener('resize', () => move(current, true));
    move(nav.querySelector('a.item-link.active') || links[0], true);
})();
