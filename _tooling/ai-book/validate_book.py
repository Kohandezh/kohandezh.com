# ---------------------------------------------------------------- kdj-hash-1
_ZW_REMOVE = re.compile('[​‍﻿⁠‎‏‪-‮⁦-⁩]')
_INTRA_WS = re.compile('[ \t ]+')


def canonical_text(s: str) -> str:
    """kdj-hash-1 normalisation (ZWNJ U+200C is kept)."""
    s = unicodedata.normalize('NFC', s or '').replace('\r\n', '\n').replace('\r', '\n')
    s = _ZW_REMOVE.sub('', s)
    s = '\n'.join(_INTRA_WS.sub(' ', line).rstrip() for line in s.split('\n'))
    return re.sub(r'\n{3,}', '\n\n', s).strip('\n')


def content_hash(section: dict) -> str:
    payload = '\n'.join([section['structural_id'], section['locale'], section['origin'],
                         canonical_text(section['title_fa']), canonical_text(section['title_en']),
                         canonical_text(section['fa_text'])])
    return hashlib.sha256(payload.encode('utf-8')).hexdigest()


def merkle(hashes_hex: list) -> str:
    def h(b: bytes) -> str:
        return hashlib.sha256(b).hexdigest()
    if not hashes_hex:
        return h(b'\x00')
    level = [h(b'\x00' + bytes.fromhex(x)) for x in hashes_hex]
    while len(level) > 1:
        level = [h(b'\x01' + bytes.fromhex(level[i]) + bytes.fromhex(level[i + 1])) if i + 1 < len(level) else level[i]
                 for i in range(0, len(level), 2)]
    return level[0]


# ---------------------------------------------------------------- reader Markdown model
_DIGITS = str.maketrans('۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789')
_FN_DEF = re.compile(r'^\s*\[\^([^\]]*)\]:\s*(.*)$')
_FN_REF = re.compile(r'\[\^([^\]]*)\]')
_FN_LEGACY = re.compile(r'(?:^|\s)>\s*([0-9۰-۹]{1,3})(?![0-9۰-۹])\s*')
_TABLE_START = re.compile(r'^\|.*\|$')
_TABLE_LINE = re.compile(r'^\s*\|.*\|\s*$')
_HEADING = re.compile(r'^(#{1,6})\s+(.+)$')
_FIGURE = re.compile(r'\[FIGURE\b', re.I)
_FIGURE_LINE = re.compile(r'^\[FIGURE\b', re.I)
# http(s) links render as anchors (BOOK-FORMAT §6); images and other schemes print literally.
_LINK = re.compile(r'!\[[^\]]*\]\([^)\s]+\)|\[[^\]^][^\]]*\]\((?!https?://)[^)\s]+\)')
_HTML = re.compile(r'</?[A-Za-z][A-Za-z0-9]*(?:\s[^<>]*)?/?>')


def footnote_numbers(label: str) -> list:
    pieces = re.split(r'[\s,،]+', label.translate(_DIGITS).strip())
    if not all(re.fullmatch(r'[0-9]{1,4}', p) for p in pieces):
        return []
    return [str(int(p)) for p in pieces]


def reader_document(text: str) -> dict:
    """Mirror of KBK_AI_Book::reader_document(): body lines, notes, refs."""
    lines, notes, loose = [], set(), 0
    for line in re.split(r'\r\n|\r|\n', text):
        m = _FN_DEF.match(line)
        if not m:
            lines.append(line)
            continue
        label, body = m.group(1).translate(_DIGITS).strip(), m.group(2).strip()
        if re.fullmatch(r'[0-9]{1,4}', label):
            if body:
                notes.add(str(int(label)))
            continue
        pieces = _FN_LEGACY.split(' ' + body)
        for i in range(1, len(pieces) - 1, 2):
            if pieces[i + 1].strip():
                notes.add(str(int(pieces[i].translate(_DIGITS))))
        loose += 1
    refs, orphan_labels = set(), 0
    for line in lines:
        for label in _FN_REF.findall(line):
            numbers = footnote_numbers(label)
            refs.update(numbers)
            orphan_labels += 0 if numbers else 1
    return {'lines': lines, 'notes': notes, 'refs': refs, 'orphan_labels': orphan_labels}


def split_table_row(line: str) -> list:
    line = line.strip()
    if line.startswith('|'):
        line = line[1:]
    if line.endswith('|') and not line.endswith('\\|'):
        line = line[:-1]
    return [c.strip() for c in re.split(r'(?<!\\)\|', line)]


def tables_of(lines: list) -> list:
    out, i = [], 0
    while i < len(lines):
        if _TABLE_START.match(lines[i].strip()):
            rows = []
            while i < len(lines) and _TABLE_LINE.match(lines[i]):
                rows.append(split_table_row(lines[i]))
                i += 1
            out.append(rows)
            continue
        i += 1
    return out


# ---------------------------------------------------------------- reporting
class Check:
    def __init__(self, name: str):
        self.name, self.fails, self.warns, self.checked, self.notes, self.skipped = name, [], [], 0, [], None

    def fail(self, msg: str) -> None:
        self.fails.append(msg)

    def warn(self, msg: str) -> None:
        self.warns.append(msg)

    def skip(self, why: str) -> 'Check':
        self.skipped = why
        return self

    @property
    def status(self) -> str:
        if self.skipped:
            return 'SKIP'
        return 'FAIL' if self.fails else 'WARN' if self.warns else 'PASS'

    def as_dict(self) -> dict:
        problems = self.fails or self.warns
        return {'name': self.name, 'status': self.status,
                'count': len(problems) if problems else self.checked,
                'examples': (self.fails + self.warns)[:3],
                'detail': self.skipped or '; '.join(self.notes)}


class Ctx:
    def __init__(self, root: Path, strict: bool, require_build: bool, slug, code):
        self.root, self.strict, self.require_build, self.slug, self.code = root, strict, require_build, slug, code
        self.data, self.raw_book, self.templates = {}, None, {}
        self.sections, self.chapters = [], []          # [(part, chapter, section)], [(part, chapter)]
        self.by_sid, self.by_cid = {}, {}
        self.doc_keys = set()
        self.overlay_applies = False
        self.edition = None


def is_type(value, types) -> bool:
    if bool in types or not isinstance(value, bool):
        return isinstance(value, types)
    return False


def non_empty(value) -> bool:
    return isinstance(value, str) and value.strip() != ''


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as fh:
        for block in iter(lambda: fh.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def url_ok(url, ctx: Ctx, part_slug=None, chapter_slug=None, fragment=None) -> bool:
    """https://kohandezh.com/fa/books/{slug}/{part}/{chapter}/#{sid} (legacy: /fa/ai-book/…)."""
    if not isinstance(url, str):
        return False
    u = urlsplit(url)
    if u.scheme != 'https' or u.netloc != 'kohandezh.com' or (fragment is not None and u.fragment != fragment):
        return False
    prefixes = ['/fa/books/%s/' % ctx.slug]
    if ctx.slug == LEGACY_SLUG:
        prefixes.append('/fa/ai-book/')
    if part_slug is None:
        return any(u.path.startswith(p) for p in prefixes)
    return u.path in ['%s%s/%s/' % (p, part_slug, chapter_slug) for p in prefixes]


# ---------------------------------------------------------------- checks
def check_files(ctx: Ctx) -> Check:
    c = Check('files')
    root = ctx.root
    tpls = sorted(root.glob(TEMPLATE_GLOB))
    groups = [(REQUIRED_FILES, 'required'), (BUILD_FILES, 'build'), (OPTIONAL_FILES, 'optional')]
    for files, kind in groups:
        for rel in files:
            p = root / rel
            if not p.is_file():
                if kind == 'required' or ctx.strict or (kind == 'build' and ctx.require_build):
                    c.fail('missing %s file %s' % (kind, rel))
                elif kind == 'build':
                    c.warn('build output %s absent (gitignored in the repo; required in the upload)' % rel)
                else:
                    c.notes.append('optional %s absent' % rel)
                continue
            c.checked += 1
            try:
                if rel.endswith('.pdf'):
                    with open(p, 'rb') as fh:
                        if fh.read(5) != b'%PDF-':
                            c.fail('%s has no %%PDF- header' % rel)
                    continue
                if rel.endswith('.jsonl'):
                    rows = []
                    with open(p, encoding='utf-8') as fh:
                        for n, line in enumerate(fh, 1):
                            if line.strip():
                                obj = json.loads(line)
                                if not isinstance(obj, dict):
                                    raise ValueError('line %d is not an object' % n)
                                rows.append(obj)
                    ctx.data[rel] = rows
                    continue
                raw = p.read_bytes()
                if rel == 'master/book.json':
                    ctx.raw_book = raw
                ctx.data[rel] = json.loads(raw.decode('utf-8'))
                expect = list if rel == 'master/source_map.json' else dict
                if not isinstance(ctx.data[rel], expect):
                    c.fail('%s top level must be a JSON %s' % (rel, 'array' if expect is list else 'object'))
                    ctx.data.pop(rel)
            except (ValueError, UnicodeDecodeError) as e:
                c.fail('%s does not parse: %s' % (rel, str(e)[:80]))
                ctx.data.pop(rel, None)
    if not tpls:
        c.fail('no %s template files' % TEMPLATE_GLOB)
    for p in tpls:
        c.checked += 1
        try:
            obj = json.loads(p.read_text(encoding='utf-8'))
            if not isinstance(obj, dict):
                raise ValueError('not an object')
            ctx.templates[p.stem] = obj
        except ValueError as e:
            c.fail('templates/%s does not parse: %s' % (p.name, str(e)[:80]))
    c.notes.append('%d files parsed, %d templates' % (c.checked - len(tpls), len(tpls)))
    return c


def check_book_top(ctx: Ctx) -> Check:
    c = Check('book.top_level')
    book = ctx.data.get('master/book.json')
    if not isinstance(book, dict):
        return c.skip('book.json not loaded')
    for field, types in BOOK_FIELDS.items():
        c.checked += 1
        if field not in book:
            c.fail('book.%s missing' % field)
        elif not is_type(book[field], types):
            c.fail('book.%s must be %s' % (field, '/'.join(t.__name__ for t in types)))
    if c.fails:
        return c
    if not EDITION_RE.match(book['edition_id']):
        c.fail('edition_id %r is not \\d{4}E\\d+' % book['edition_id'])
    else:
        ctx.edition = book['edition_id']
    if book['locale'] != 'fa':
        c.fail('locale must be "fa"')
    for f in ('title_fa', 'compiler', 'attribution', 'built_at'):
        if not non_empty(book[f]):
            c.fail('book.%s must be a non-empty string' % f)
    if book['hash_spec'] != HASH_SPEC:
        c.fail('hash_spec %r is not %s (the only spec this validator knows)' % (book['hash_spec'], HASH_SPEC))
    if not HEX64_RE.match(book['merkle_root']):
        c.fail('merkle_root is not 64 lowercase hex')
    if not book['parts']:
        c.fail('parts is empty')
    if 'coverage' in book and not isinstance(book['coverage'], dict):
        c.fail('coverage must be an object when present')
    if book['units'] < 1:
        c.fail('units must be a positive integer')
    return c


def check_book_structure(ctx: Ctx) -> Check:
    c = Check('book.structure')
    book = ctx.data.get('master/book.json')
    if not isinstance(book, dict) or not isinstance(book.get('parts'), list):
        return c.skip('book.json parts not loaded')
    chapter_no, seen_chapters = 0, set()
    for pi, part in enumerate(book['parts'], 1):
        if not isinstance(part, dict):
            c.fail('parts[%d] is not an object' % (pi - 1))
            continue
        for field, types in PART_FIELDS.items():
            if field not in part or not is_type(part[field], types):
                c.fail('part %s.%s missing or not %s' % (part.get('part_id', pi), field, types[0].__name__))
        if part.get('part_id') != 'P%02d' % pi:
            c.fail('parts[%d].part_id %r != P%02d (position)' % (pi - 1, part.get('part_id'), pi))
        slug = part.get('slug')
        if not isinstance(slug, str) or not PATH_SLUG_RE.match(slug) or len(slug) > 80:
            c.fail('part %s slug %r breaks the slug grammar' % (part.get('part_id'), slug))
        elif slug in RESERVED_PART_SLUGS:
            c.fail('part %s slug %r is a reserved view name' % (part.get('part_id'), slug))
        if not non_empty(part.get('title_fa')):
            c.fail('part %s title_fa empty' % part.get('part_id'))
        if isinstance(part.get('part_hash'), str) and not HEX64_RE.match(part['part_hash']):
            c.fail('part %s part_hash is not 64 hex' % part.get('part_id'))
        chapters = part.get('chapters') if isinstance(part.get('chapters'), list) else []
        if not chapters:
            c.fail('part %s has no chapters' % part.get('part_id'))
        slugs: dict = {}
        for chapter in chapters:
            chapter_no += 1
            c.checked += 1
            if not isinstance(chapter, dict):
                c.fail('a chapter of %s is not an object' % part.get('part_id'))
                continue
            cid = chapter.get('chapter_id')
            for field, types in CHAPTER_FIELDS.items():
                if field not in chapter or not is_type(chapter[field], types):
                    c.fail('chapter %s.%s missing or not %s' % (cid, field, '/'.join(t.__name__ for t in types)))
            if cid != 'C%02d' % chapter_no:
                c.fail('chapter %r != C%02d (chapters are numbered book-wide)' % (cid, chapter_no))
            if cid in seen_chapters:
                c.fail('chapter_id %s repeats' % cid)
            seen_chapters.add(cid)
            cslug = chapter.get('slug')
            if not isinstance(cslug, str) or not PATH_SLUG_RE.match(cslug) or len(cslug) > 80:
                c.fail('chapter %s slug %r breaks the slug grammar' % (cid, cslug))
            else:
                slugs.setdefault(cslug, []).append(cid)
            if chapter.get('origin') not in ORIGINS:
                c.fail('chapter %s origin %r not allowed' % (cid, chapter.get('origin')))
            if isinstance(chapter.get('kind'), str) and chapter['kind'] not in CHAPTER_KINDS:
                c.warn('chapter %s kind %r is not one of %s' % (cid, chapter['kind'], sorted(CHAPTER_KINDS)))
            if not non_empty(chapter.get('title_fa')):
                c.fail('chapter %s title_fa empty' % cid)
            if isinstance(chapter.get('chapter_hash'), str) and not HEX64_RE.match(chapter['chapter_hash']):
                c.fail('chapter %s chapter_hash is not 64 hex' % cid)
            sections = chapter.get('sections') if isinstance(chapter.get('sections'), list) else []
            if not sections:
                c.fail('chapter %s has no sections' % cid)
            if len(sections) > 99:
                c.fail('chapter %s has %d sections (max 99)' % (cid, len(sections)))
            ctx.chapters.append((part, chapter))
            for si, section in enumerate(sections, 1):
                if not isinstance(section, dict):
                    c.fail('%s section %d is not an object' % (cid, si))
                    continue
                if section.get('section_id') != 'S%02d' % si:
                    c.fail('%s sections[%d].section_id %r != S%02d' % (cid, si - 1, section.get('section_id'), si))
                ctx.sections.append((part, chapter, section))
        for cslug, ids in slugs.items():
            if len(ids) > 1:
                c.warn('chapter slug %r is shared by %s in %s: their canonical_url path cannot be resolved'
                       % (cslug, ', '.join(ids), part.get('part_id')))
    if len(book['parts']) > 99 or chapter_no > 99:
        c.fail('%d parts / %d chapters exceed the two-digit limit (99)' % (len(book['parts']), chapter_no))
    if isinstance(book.get('units'), int) and book['units'] != len(ctx.sections):
        c.fail('units=%s but the book holds %d sections' % (book['units'], len(ctx.sections)))
    c.notes.append('%d parts, %d chapters, %d sections' % (len(book['parts']), chapter_no, len(ctx.sections)))
    return c


def check_section_fields(ctx: Ctx) -> Check:
    c = Check('book.section_fields')
    if not ctx.sections:
        return c.skip('no sections loaded')
    for part, chapter, s in ctx.sections:
        c.checked += 1
        sid = s.get('structural_id', '?')
        for field, types in SECTION_FIELDS.items():
            if field not in s:
                c.fail('%s.%s missing' % (sid, field))
            elif not is_type(s[field], types):
                c.fail('%s.%s must be %s' % (sid, field, '/'.join(t.__name__ for t in types)))
        if s.get('locale') != 'fa':
            c.fail('%s.locale must be "fa"' % sid)
        if s.get('origin') not in ORIGINS:
            c.fail('%s.origin %r not allowed' % (sid, s.get('origin')))
        for f in ('title_fa', 'fa_text'):
            if f in s and not non_empty(s[f]):
                c.fail('%s.%s is empty' % (sid, f))
        if s.get('part_id') != part.get('part_id') or s.get('chapter_id') != chapter.get('chapter_id'):
            c.fail('%s part_id/chapter_id disagree with its position' % sid)
        docs = s.get('source_documents')
        if isinstance(docs, list):
            if not all(isinstance(d, str) for d in docs):
                c.fail('%s.source_documents must hold strings' % sid)
            elif ctx.doc_keys and any(d not in ctx.doc_keys for d in docs):
                c.warn('%s cites a document missing from manifests/sources.json' % sid)
    return c


def check_ids(ctx: Ctx) -> Check:
    c = Check('ids.grammar')
    if not ctx.sections:
        return c.skip('no sections loaded')
    codes = set()
    for part, chapter, s in ctx.sections:
        c.checked += 1
        sid, cid = s.get('structural_id'), s.get('content_id')
        m = STRUCTURAL_RE.match(sid) if isinstance(sid, str) else None
        if not m:
            c.fail('structural_id %r breaks KDJ-{CODE}-{EDITION}-Pnn-Cnn-Snn' % sid)
            continue
        codes.add(m.group(1))
        expect = 'KDJ-%s-%s-%s-%s-%s' % (m.group(1), ctx.edition, part.get('part_id'), chapter.get('chapter_id'),
                                         s.get('section_id'))
        if sid != expect:
            c.fail('structural_id %s != %s (edition/position)' % (sid, expect))
        if s.get('citation_id') != sid:
            c.fail('%s citation_id %r != structural_id' % (sid, s.get('citation_id')))
        cm = CONTENT_RE.match(cid) if isinstance(cid, str) else None
        if not cm or cm.group(1) != sid:
            c.fail('content_id %r is not structural_id + "-" + HASH8' % cid)
        else:
            ch = s.get('content_hash', '')
            if isinstance(ch, str) and ch.startswith('sha256:') and HEX64_RE.match(ch[7:]):
                if cm.group(2) != ch[7:15].upper():
                    c.fail('%s HASH8 %s != content_hash[:8] %s' % (sid, cm.group(2), ch[7:15].upper()))
            else:
                c.fail('%s content_hash %r is not "sha256:" + 64 hex' % (sid, ch))
        if sid in ctx.by_sid:
            c.fail('structural_id %s repeats' % sid)
        if cid in ctx.by_cid:
            c.fail('content_id %s repeats' % cid)
        ctx.by_sid[sid], ctx.by_cid[cid] = s, s
        if not url_ok(s.get('canonical_url'), ctx, part.get('slug'), chapter.get('slug'), sid):
            c.fail('%s canonical_url %r is not https://kohandezh.com/fa/books/%s/{part_slug}/{chapter_slug}/#%s'
                   % (sid, s.get('canonical_url'), ctx.slug, sid))
    if len(codes) > 1:
        c.fail('more than one ID code in one book: %s' % sorted(codes))
    if ctx.code and codes and codes != {ctx.code}:
        c.fail('ID code %s != expected %s' % (sorted(codes), ctx.code))
    c.notes.append('code %s, slug %s' % ('/'.join(sorted(codes)) or '?', ctx.slug))
    return c


