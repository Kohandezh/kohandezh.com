def check_merkle(ctx: Ctx) -> Check:
    c = Check('ids.merkle')
    book = ctx.data.get('master/book.json')
    if not ctx.sections or not isinstance(book, dict):
        return c.skip('no sections loaded')
    part_hashes = []
    try:
        for part in book['parts']:
            chapter_hashes = []
            for chapter in part['chapters']:
                root = merkle([s['content_hash'].split(':', 1)[1] for s in chapter['sections']])
                c.checked += 1
                if root != chapter.get('chapter_hash'):
                    c.fail('%s chapter_hash does not match its sections' % chapter.get('chapter_id'))
                chapter_hashes.append(root)
            root = merkle(chapter_hashes)
            if root != part.get('part_hash'):
                c.fail('%s part_hash does not match its chapters' % part.get('part_id'))
            part_hashes.append(root)
        if merkle(part_hashes) != book.get('merkle_root'):
            c.fail('merkle_root does not match the parts')
    except (KeyError, TypeError, ValueError, AttributeError) as e:
        c.fail('tree is not hashable: %s' % e)
    return c


