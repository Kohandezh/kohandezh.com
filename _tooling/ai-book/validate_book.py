def check_release_manifest(ctx: Ctx) -> Check:
    c = Check('provenance.release_manifest')
    man = ctx.data.get('provenance/release-manifest.json')
    book = ctx.data.get('master/book.json')
    if not isinstance(man, dict) or not isinstance(book, dict):
        return c.skip('release-manifest.json or book.json not loaded')
    for k in MANIFEST_REQUIRED:
        c.checked += 1
        if k not in man:
            c.fail('release-manifest.%s missing' % k)
    for k in MANIFEST_RECOMMENDED:
        if k not in man:
            c.warn('release-manifest.%s missing (pipeline provenance)' % k)
    if c.fails:
        return c
    if not non_empty(man['build_date']) or len(man['build_date']) > 32:
        c.fail('build_date must be a non-empty string <= 32 chars')
    if not non_empty(man['publisher']) or len(man['publisher']) > 120:
        c.fail('publisher must be a non-empty string <= 120 chars')
    if man['hash_spec'] != book.get('hash_spec'):
        c.fail('hash_spec %r != book %r' % (man['hash_spec'], book.get('hash_spec')))
    if man['merkle_root'] != book.get('merkle_root'):
        c.fail('merkle_root differs from book.json')
    arts = man['artifacts']
    if not isinstance(arts, dict) or not 1 <= len(arts) <= 32:
        c.fail('artifacts must be an object of 1..32 entries')
        return c
    if '06_book_fa.pdf' not in arts:
        c.fail('artifacts must list 06_book_fa.pdf')
    for name, a in arts.items():
        if not isinstance(a, dict) or not isinstance(a.get('bytes'), int) or not HEX64_RE.match(str(a.get('sha256'))):
            c.fail('artifacts.%s needs {bytes:int, sha256:64 hex}' % name)
    md = man['missing_deliverables']
    if not isinstance(md, list) or len(md) > 50 or not all(isinstance(x, str) and len(x) <= 200 for x in md):
        c.fail('missing_deliverables must be a list of <= 50 short strings')
    if ctx.raw_book is not None:
        actual = hashlib.sha256(ctx.raw_book).hexdigest()
        if man['master_json_sha256'] != actual:
            c.warn('master_json_sha256 != sha256(book.json): book.json is not the signed bytes '
                   '(edited or reformatted); the overlay and verification depend on them')
        else:
            c.notes.append('book.json is byte-identical to the signed master')
    for name, rel in RELEASE_ARTIFACT_PATHS.items():
        a, p = arts.get(name), ctx.root / rel
        if not isinstance(a, dict) or not p.is_file() or rel.endswith('.pdf'):
            continue  # the PDF is checked by pdf.file
        c.checked += 1
        if p.stat().st_size != a.get('bytes') or sha256_file(p) != a.get('sha256'):
            c.warn('%s is not byte-identical to release artifact %s' % (rel, name))
    return c


def check_overlay(ctx: Ctx) -> Check:
    c = Check('overlay')
    ov = ctx.data.get('master/reader-overlay.json')
    if ov is None:
        return c.skip('no master/reader-overlay.json (canonical text is rendered)')
    if not ctx.by_sid:
        return c.skip('sections not loaded')
    if ov.get('schema') != OVERLAY_SCHEMA:
        c.fail('schema %r != %s' % (ov.get('schema'), OVERLAY_SCHEMA))
    if ov.get('edition_id') != ctx.edition:
        c.fail('edition_id %r != book %s' % (ov.get('edition_id'), ctx.edition))
    actual = hashlib.sha256(ctx.raw_book or b'').hexdigest()
    if ov.get('book_sha256') != actual:
        c.fail('book_sha256 is stale (overlay %s…, book.json %s…): the reader ignores the whole overlay'
               % (str(ov.get('book_sha256'))[:12], actual[:12]))
    if not non_empty(ov.get('generator')):
        c.warn('generator is missing')
    ctx.overlay_applies = not c.fails
    chapter_ids = {ch.get('chapter_id') for _, ch in ctx.chapters}
    chapters = ov.get('chapters', {})
    if not isinstance(chapters, dict):
        c.fail('chapters must be an object')
        chapters = {}
    for key, patch in chapters.items():
        c.checked += 1
        if key not in chapter_ids:
            c.fail('chapters.%s is not a chapter of the book' % key)
        elif not isinstance(patch, dict) or not non_empty(patch.get('title_fa')) or set(patch) - {'title_fa'}:
            c.fail('chapters.%s must be {title_fa: non-empty string}' % key)
    sections = ov.get('sections', {})
    if not isinstance(sections, dict):
        c.fail('sections must be an object')
        sections = {}
    unmatched = 0
    for key, patch in sections.items():
        c.checked += 1
        if key not in ctx.by_sid:
            c.fail('sections.%s is not a structural_id of the book' % key)
            continue
        if not isinstance(patch, dict) or not patch or set(patch) - {'title_fa', 'fa_text', 'omit'}:
            c.fail('sections.%s must hold only title_fa / fa_text / omit' % key)
            continue
        for f in ('title_fa', 'fa_text'):
            if f in patch and not non_empty(patch[f]):
                c.fail('sections.%s.%s must be a non-empty string' % (key, f))
        if 'omit' in patch and patch['omit'] is not True:
            c.fail('sections.%s.omit must be true when present' % key)
        if isinstance(patch.get('fa_text'), str):
            doc = reader_document(patch['fa_text'])
            missing = sorted(doc['refs'] - doc['notes'], key=int)
            if missing:
                unmatched += len(missing)
                c.warn('sections.%s fa_text references [^%s] with no definition' % (key, ','.join(missing[:5])))
    c.notes.append('%d chapter + %d section patches; applies=%s; %d unmatched footnote refs'
                   % (len(chapters), len(sections), ctx.overlay_applies, unmatched))
    return c


def rendered_sections(ctx: Ctx):
    """(structural_id, text) exactly as the reader shows it: overlay applied when valid, omitted skipped."""
    patches = (ctx.data.get('master/reader-overlay.json') or {}).get('sections', {}) if ctx.overlay_applies else {}
    for _, _, s in ctx.sections:
        patch = patches.get(s.get('structural_id')) if isinstance(patches, dict) else None
        patch = patch if isinstance(patch, dict) else {}
        if patch.get('omit') is True:
            continue
        text = patch.get('fa_text') if non_empty(patch.get('fa_text')) else s.get('fa_text')
        if isinstance(text, str):
            yield s.get('structural_id'), text


