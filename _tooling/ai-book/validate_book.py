def infer_slug(ctx: Ctx):
    book = ctx.data.get('master/book.json')
    try:
        url = book['parts'][0]['chapters'][0]['sections'][0]['canonical_url']
    except (KeyError, IndexError, TypeError):
        return LEGACY_SLUG
    m = re.match(r'^https://kohandezh\.com/fa/books/([a-z0-9-]+)/', str(url))
    return m.group(1) if m else LEGACY_SLUG


def validate(root, strict=False, require_build=False, slug=None, code=None) -> dict:
    """Run every check; returns the report dict (see --json)."""
    started = time.time()
    ctx = Ctx(Path(root), strict, require_build or strict, slug, code)
    results = []
    for fn in CHECKS:
        result = fn(ctx)
        if fn is check_files and ctx.slug is None:
            ctx.slug = infer_slug(ctx)
        results.append(result.as_dict())
    if not BOOK_SLUG_RE.match(ctx.slug or '') or len(ctx.slug) > 40:
        results.append({'name': 'registry.slug', 'status': 'FAIL', 'count': 1,
                        'examples': ['slug %r breaks ^[a-z0-9]+(-[a-z0-9]+)*$ (<= 40)' % ctx.slug], 'detail': ''})
    summary = {s: sum(1 for r in results if r['status'] == s) for s in ('PASS', 'WARN', 'FAIL', 'SKIP')}
    return {'format': FORMAT, 'root': str(ctx.root), 'slug': ctx.slug, 'strict': strict,
            'require_build': ctx.require_build, 'checks': results, 'summary': summary,
            'seconds': round(time.time() - started, 2), 'exit': 1 if summary['FAIL'] else 0}


def print_report(report: dict, out=sys.stdout) -> None:
    print('%s  %s  (slug %s%s)' % (report['format'], report['root'], report['slug'],
                                  ', strict' if report['strict'] else ''), file=out)
    for r in report['checks']:
        print('  %-4s  %-32s %6d  %s' % (r['status'], r['name'], r['count'], r['detail']), file=out)
        if r['status'] in ('WARN', 'FAIL'):
            for ex in r['examples']:
                print('          - %s' % ex, file=out)
    s = report['summary']
    print('Result: %d PASS, %d WARN, %d FAIL, %d SKIP in %.1f s -> exit %d'
          % (s['PASS'], s['WARN'], s['FAIL'], s['SKIP'], report['seconds'], report['exit']), file=out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description='Validate a Kohandezh book bundle (Books/BOOK-FORMAT.md).')
    ap.add_argument('--root', default=str(REPO / 'Books' / 'ai-governance'))
    ap.add_argument('--strict', action='store_true', help='missing build or optional files are FAILs')
    ap.add_argument('--release', action='store_true', help='missing build outputs (PDF, search index) are FAILs')
    ap.add_argument('--slug', help='registry slug (default: inferred from canonical_url)')
    ap.add_argument('--code', help='ID code, e.g. AI (default: inferred)')
    ap.add_argument('--json', action='store_true', help='print the report as JSON')
    args = ap.parse_args(argv)
    root = Path(args.root)
    if not root.is_dir():
        print('validate_book: --root %s is not a directory' % root, file=sys.stderr)
        return 2
    if args.code and not CODE_RE.match(args.code):
        print('validate_book: --code must match [A-Z0-9]{1,8}', file=sys.stderr)
        return 2
    report = validate(root, args.strict, args.release, args.slug, args.code)
    if args.json:
        json.dump(report, sys.stdout, ensure_ascii=False, indent=1)
        print()
    else:
        print_report(report)
    return report['exit']


if __name__ == '__main__':
    sys.exit(main())
